func TestParseSPDP(t *testing.T) {
	pkt, err := Parse(rtpsRead1)
	require.NoError(t, err)
	require.Equal(t, "2.1", pkt.Version)
	require.Equal(t, "0110", pkt.VendorID)
	require.Equal(t, "Eclipse Cyclone DDS", pkt.Vendor)
	require.Equal(t, "01105c8e2cd45847fa5a30d3", pkt.GUIDPrefix)
	require.Equal(t, []Submessage{
		{Kind: "INFO_TS", Flags: 1, Length: 8},
		{Kind: "DATA", Flags: 5, Length: 192},
	}, pkt.Submessages)
	require.Equal(t, "DATA(p)", pkt.Command)
	require.Equal(t, "000100c2", pkt.WriterEntityID)
	require.EqualValues(t, 1, pkt.WriterSN)
	require.Equal(t, "01105c8e2cd45847fa5a30d3000001c1", pkt.ParticipantGUID)
	require.Equal(t, "DDSPerf:0:58:test.local", pkt.UserData)
	require.NotNil(t, pkt.DomainID)
	require.EqualValues(t, 0, *pkt.DomainID)
	require.Equal(t, []string{"0x8007=test.local/0.9.0/Linux/Linux"}, pkt.VendorStrings)
}

func TestParseTruncated(t *testing.T) {
	for _, n := range []int{4, 19, 21, 30, 60, 227} {
		_, err := Parse(rtpsRead1[:n])
		require.ErrorIs(t, err, ErrTruncated, "len %d", n)
	}
	// Cut inside the parameter list: header and submessages still parse.
	pkt, err := Parse(rtpsRead1[:100])
	require.ErrorIs(t, err, ErrTruncated)
	require.Equal(t, "2.1", pkt.Version)
	require.Equal(t, "INFO_TS", pkt.Submessages[0].Kind)
}

func TestParseNotRTPS(t *testing.T) {
	_, err := Parse([]byte("GET / HTTP/1.1\r\n\r\n"))
	require.ErrorIs(t, err, ErrNotRTPS)
	_, err = Parse(nil)
	require.ErrorIs(t, err, ErrNotRTPS)
}

func TestParseLastSubmessageZeroLength(t *testing.T) {
	data := append([]byte("RTPS\x02\x02\x01\x0f"), make([]byte, 12)...)
	data = append(data, 0x07, 0x01, 0x00, 0x00, 1, 2, 3, 4) // HEARTBEAT, length 0 = to end
	pkt, err := Parse(data)
	require.NoError(t, err)
	require.Equal(t, "HEARTBEAT", pkt.Command)
	require.Equal(t, "eProsima Fast DDS", pkt.Vendor)
	require.Equal(t, 4, pkt.Submessages[0].Length)
}

func TestParseBogusParamLengths(t *testing.T) {
	data := append([]byte(nil), rtpsRead1...)
	data[0x3c+2] = 0xff // PID_USER_DATA length points past the end
	pkt, err := Parse(data)
	require.NoError(t, err)
	require.Empty(t, pkt.UserData)
}

func TestLooksLikeRTPS(t *testing.T) {
	require.True(t, LooksLikeRTPS(rtpsRead1))
	require.False(t, LooksLikeRTPS(rtpsRead1[:19]))
	require.False(t, LooksLikeRTPS([]byte("RTSP/1.0 200 OK\r\nCSeq: 1\r\n\r\n")))
}
