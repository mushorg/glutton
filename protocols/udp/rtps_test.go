func runRTPS(t *testing.T, payload []byte) (*recordingHoneypot, []parsedRTPS) {
	t.Helper()
	h := &recordingHoneypot{}
	src := &net.UDPAddr{IP: net.ParseIP("203.0.113.10"), Port: 26310}
	dst := &net.UDPAddr{IP: net.ParseIP("198.51.100.1"), Port: 7400}
	require.NoError(t, HandleRTPS(context.Background(), src, dst, payload, connection.Metadata{}, testLogger{}, h))
	require.Len(t, h.produced, 1)
	require.Equal(t, "rtps", h.produced[0].handler)
	require.Empty(t, h.replies)
	events, ok := h.produced[0].decoded.([]parsedRTPS)
	require.True(t, ok)
	return h, events
}

func TestHandleRTPSSPDP(t *testing.T) {
	h, events := runRTPS(t, rtpsRead1)
	require.Equal(t, rtpsRead1, h.produced[0].payload)
	require.Len(t, events, 1)
	ev := events[0]
	require.Equal(t, "read", ev.Direction)
	require.Equal(t, "DATA(p)", ev.Command)
	require.Equal(t, "2.1", ev.Version)
	require.Equal(t, "0110", ev.VendorID)
	require.Equal(t, "01105c8e2cd45847fa5a30d3", ev.GUIDPrefix)
	require.Len(t, ev.Submessages, 2)
	require.Equal(t, "000100c2", ev.WriterEntityID)
	require.Equal(t, "DDSPerf:0:58:test.local", ev.UserData)
	require.Equal(t, []string{"0x8007=test.local/0.9.0/Linux/Linux"}, ev.VendorStrings)
	require.Equal(t, rtpsRead1, ev.Payload)
	require.False(t, ev.Truncated)
}

func TestHandleRTPSTruncated(t *testing.T) {
	payload := rtpsRead1[:40]
	_, events := runRTPS(t, payload)
	require.Len(t, events, 1)
	require.Equal(t, "2.1", events[0].Version)
	require.Equal(t, payload, events[0].Payload)
}

func TestHandleRTPSMalformed(t *testing.T) {
	payload := []byte{0x00, 0x01, 0x02, 0x03}
	_, events := runRTPS(t, payload)
	require.Len(t, events, 1)
	require.Equal(t, "UNKNOWN", events[0].Command)
	require.Equal(t, payload, events[0].Payload)
}

func TestHandleRTPSEmpty(t *testing.T) {
	h, events := runRTPS(t, nil)
	require.Empty(t, events)
	require.Empty(t, h.produced[0].payload)
}

func TestHandleRTPSOversize(t *testing.T) {
	payload := append(append([]byte(nil), rtpsRead1...), make([]byte, 2000)...)
	_, events := runRTPS(t, payload)
	require.Len(t, events[0].Payload, maxRTPSPayload)
	require.True(t, events[0].Truncated)
}

func TestHandleUDPRoutesRTPS(t *testing.T) {
	h := &recordingHoneypot{}
	src := &net.UDPAddr{IP: net.ParseIP("203.0.113.10"), Port: 1}
	dst := &net.UDPAddr{IP: net.ParseIP("198.51.100.1"), Port: 12345}
	require.NoError(t, HandleUDP(context.Background(), src, dst, rtpsRead1, connection.Metadata{}, testLogger{}, h))
	require.Len(t, h.produced, 1)
	require.Equal(t, "rtps", h.produced[0].handler)

	h = &recordingHoneypot{}
	require.NoError(t, HandleUDP(context.Background(), src, dst, []byte("RTPS-not-really"), connection.Metadata{}, testLogger{}, h))
	require.Len(t, h.produced, 1)
	require.Equal(t, "udp", h.produced[0].handler)
}
